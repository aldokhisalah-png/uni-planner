import fs from 'node:fs';
const dir = 'supabase/functions/planner-push/';
const idx = fs.readFileSync(dir + 'index.ts', 'utf8').split('\n');
const core = fs.readFileSync(dir + 'core.js', 'utf8');
const imp = idx.findIndex(l => l.includes("from './core.js'"));
const head = idx.slice(0, imp).join('\n'), rest = idx.slice(imp + 1).join('\n');
fs.mkdirSync('supabase/dashboard-paste', { recursive: true });
fs.writeFileSync('supabase/dashboard-paste/planner-push.ts',
`// Single-file copy of supabase/functions/planner-push (index.ts + core.js) for pasting into the
// Supabase dashboard editor. Generated by \`npm run bundle\`; edit the originals, not this file.
${head}

// ===== core.js =====
${core}
// ===== index.ts =====
${rest}`);
